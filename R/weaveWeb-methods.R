#' @name weaveWeb.MultiAssayExperiment
#' @rdname weaveWeb
#' @importFrom SummarizedExperiment colData assay assayNames
#' @importFrom MultiAssayExperiment MultiAssayExperiment experiments
#' @param ... additional parameters passed to [AnansiWeb()].
#' @param force_new `boolean` If x already has a dictionary `Matrix` in
#'     metadata, ignore it and generate a new object anyway? (Default: FALSE).
#' @param tableY,tableX
#' `Character scalar` or `numeric scalar`. Selects experiment
#' corresponding to `tableY` and `tableX` from `experiments(x)` of
#' `MultiAssayExperiment` object by name or index, name is recommended.
#' (Default slots: `Y = 1L`, `X = 2L`).
#' @param typeY,typeX
#' `Character scalar` or `numeric scalar`. Selects assay from experiments to
#' `tableY` and `tableX` from `experiments(x)`. (Default: `1L` - the first assay
#'  in that experiment).
#' @param experiment1,experiment2 synonymous args to `tableY,tableX` for
#'     compatibility with `mia` argument style.
#' @param assay.type1,assay.type2 synonymous args to `typeY,typeX` for
#'     compatibility with `mia` argument style.
#' @method weaveWeb MultiAssayExperiment
#' @usage
#' # Method for MultiAssayExperiment S4 object
#'  weaveWeb.MultiAssayExperiment(
#'      x, link = NULL,
#'      tableX = NULL, tableY = NULL, typeY = NULL, typeX = NULL,
#'      force_new = FALSE,
#'      experiment1 = NULL, experiment2 = NULL,
#'      assay.type1 = NULL, assay.type2 = NULL
#'  )
#'
S7::method(
    weaveWeb,
    methods::getClass( "MultiAssayExperiment", where = "MultiAssayExperiment")
) <- function(
        x,
        link = NULL,
        tableY = NULL,
        tableX = NULL,
        typeY = NULL,
        typeX = NULL,
        force_new = FALSE,
        experiment1 = NULL,
        experiment2 = NULL,
        assay.type1 = NULL,
        assay.type2 = NULL
) {
    y_ids <- .test_coherent(tableY, experiment1, typeY, assay.type1)
    x_ids <- .test_coherent(tableX, experiment2, typeX, assay.type2)
    tableY <- y_ids[[1L]]
    tableX <- x_ids[[1L]]

    # Check experiments
    .test_mae_has_exp(x, tableY)
    .test_mae_has_exp(x, tableX)

    # Extract assays
    tY <- t(assay(experiments(x)[tableY], y_ids[[2L]]))
    tX <- t(assay(experiments(x)[tableX], x_ids[[2L]]))

    # Check if x already contains a dictionary
    if (!force_new) {
        m <- x@metadata

        d <- if( is.null(link) ) {"dictionary"} else {""}
        if (.check_valid_selection(link, m)) {
            d <- link
        }
        if (d %in% names(m)) {
            return(AnansiWeb(
                tableX = tX,
                tableY = tY,
                dictionary = m[[d]],
                metadata = as.data.frame(colData(x))
                ))
        }
    }
    # Else, generate web object
    weaveWeb(
        x = tableX,
        y = tableY,
        link = link,
        tableX = tX,
        tableY = tY,
        metadata = as.data.frame(colData(x))
        )
}

#' @name weaveWeb.SingleCellExperiment
#' @aliases weaveWeb.TreeSumarizedExperiment
#' @rdname weaveWeb
#' @importClassesFrom SingleCellExperiment SingleCellExperiment
#' @importFrom SummarizedExperiment colData assay assayNames
#' @importFrom SingleCellExperiment SingleCellExperiment altExp altExpNames
#' @method weaveWeb SingleCellExperiment
#' @usage
#' # Method for SingleCellExperiment S4 object
#'  weaveWeb.SingleCellExperiment(
#'      x, link = NULL,
#'      tableX = NULL, tableY = NULL, typeY = NULL, typeX = NULL,
#'      force_new = FALSE,
#'      experiment1 = NULL, experiment2 = NULL,
#'      assay.type1 = NULL, assay.type2 = NULL
#'  )
#'
S7::method(
    weaveWeb,
    methods::getClass("SingleCellExperiment", where = "SingleCellExperiment")
) <- function(
        x,
        link = NULL,
        tableY = NULL,
        tableX = NULL,
        typeY = NULL,
        typeX = NULL,
        force_new = FALSE,
        experiment1 = NULL,
        experiment2 = NULL,
        assay.type1 = NULL,
        assay.type2 = NULL
) {
    y_ids <- .test_coherent(tableY, experiment1, typeY, assay.type1)
    x_ids <- .test_coherent(tableX, experiment2, typeX, assay.type2)
    tableY <- y_ids[[1L]]
    tableX <- x_ids[[1L]]


    tse_list <- .get_table_from_tse(x, tableY, tableX)


    # Extract assays
    tY <- t(assay(tse_list[[1L]], y_ids[[2L]]))
    tX <- t(assay(tse_list[[2L]], x_ids[[2L]]))

    # Check if x already contains a dictionary
    if (!force_new) {
        m <- x@metadata

        if (is.null(link)) {
            d <- "dictionary"
        }
        if (.check_valid_selection(link, m)) {
            d <- link
        }
        if (d %in% names(m)) {
            return(AnansiWeb(
                tableX = tX,
                tableY = tY,
                dictionary = m[[d]],
                metadata = as.data.frame(colData(x))
                )
            )
        }
    }
    # Generate web object
    weaveWeb(
        x = names(tse_list)[2L],
        y = names(tse_list)[1L],
        link = link,
        tableX = tX,
        tableY = tY,
        metadata = as.data.frame(colData(x))
    )
}
